// Builds backend/Code-all-in-one.gs: web/calc.js + backend/Code.gs, the one file to paste into Apps Script.
const fs = require('fs');
const path = require('path');

const calc = fs.readFileSync(path.join(__dirname, 'web', 'calc.js'), 'utf8');
const code = fs.readFileSync(path.join(__dirname, 'backend', 'Code.gs'), 'utf8');
const banner = '// GENERATED by `npm run build` from web/calc.js and backend/Code.gs. Edit those, not this file.\n\n';
fs.writeFileSync(path.join(__dirname, 'backend', 'Code-all-in-one.gs'), banner + calc + '\n\n' + code);
console.log('Wrote backend/Code-all-in-one.gs');
